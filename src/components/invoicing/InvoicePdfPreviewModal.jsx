import { getInvoicePdfUrl, getStatusBadgeClass } from '../../service/commercialService.js'
import { formatDateOnly, formatGhs } from '../../utils/formatters.js'
import { Button } from '../Button.jsx'
import { Modal } from '../Modal.jsx'

export function InvoicePdfPreviewModal({
  open,
  onClose,
  workspace,
  workspaceSlug,
  invoice,
}) {
  const lines = Array.isArray(invoice?.line_items) ? invoice.line_items : []

  function handleDownloadPdf() {
    if (!workspaceSlug || !invoice?.id) return
    const url = getInvoicePdfUrl(workspaceSlug, invoice.id, { disposition: 'attachment' })
    const link = document.createElement('a')
    link.href = url
    link.download = `${invoice.invoice_number || `invoice-${invoice.id}`}.pdf`
    document.body.appendChild(link)
    link.click()
    link.remove()
  }

  return (
    <Modal
      open={open}
      title={invoice ? `Commercial Invoice · ${invoice.invoice_number}` : 'Invoice PDF Preview'}
      subtitle="Standard commercial invoice in Ghana Cedis (GHS)"
      maxWidthClass="max-w-xl"
      onClose={onClose}
      footer={
        <div className="w-full flex flex-wrap items-center justify-between gap-2">
          <span className="text-xs text-sub">
            Standard commercial invoice generated by jojoCRM.
          </span>
          <div className="flex items-center gap-2">
            <Button
              type="button"
              variant="secondary"
              onClick={onClose}
              className="px-4 py-1.5 text-xs"
            >
              Close
            </Button>
            <Button
              type="button"
              variant="primary"
              onClick={handleDownloadPdf}
              className="px-4 py-1.5 text-xs font-semibold"
            >
              Download PDF
            </Button>
          </div>
        </div>
      }
    >
      {invoice ? (
        <div className="p-5 rounded-lg border crm-border bg-white text-slate-900 space-y-4 text-xs shadow-inner">
          <div className="flex flex-wrap items-start justify-between gap-3 pb-3 border-b border-slate-200">
            <div>
              <div className="text-sm font-bold text-slate-900">
                {workspace?.name || 'jojoCRM Workspace'}
              </div>
              <div className="text-[11px] text-slate-500">COMMERCIAL INVOICE (GHS)</div>
            </div>
            <div className="text-right space-y-1">
              <div className="text-sm font-bold text-slate-900 num-tabular">
                {invoice.invoice_number}
              </div>
              <span className={getStatusBadgeClass(invoice.status_tone, invoice.status)}>
                {invoice.status}
              </span>
            </div>
          </div>

          <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
            <div className="space-y-0.5">
              <div className="text-[10px] font-semibold uppercase tracking-wider text-slate-500">
                Bill To
              </div>
              <div className="font-semibold text-slate-900">
                {invoice.account?.name || invoice.contact?.name || 'Customer'}
              </div>
              {invoice.account?.city ? (
                <div className="text-slate-600">{invoice.account.city}</div>
              ) : null}
              {invoice.contact?.name ? (
                <div className="text-slate-600">
                  Attn: {invoice.contact.name}
                  {invoice.contact.email ? ` (${invoice.contact.email})` : ''}
                </div>
              ) : null}
            </div>

            <div className="space-y-1 sm:text-right">
              <div>
                <span className="text-slate-500">Issue Date: </span>
                <span className="font-medium text-slate-900 num-tabular">
                  {formatDateOnly(invoice.issue_date)}
                </span>
              </div>
              <div>
                <span className="text-slate-500">Due Date: </span>
                <span className="font-medium text-slate-900 num-tabular">
                  {formatDateOnly(invoice.due_date)}
                </span>
              </div>
            </div>
          </div>

          <div className="border border-slate-200 rounded-md overflow-hidden">
            <table className="w-full text-left border-collapse">
              <thead>
                <tr className="bg-slate-50 border-b border-slate-200 text-[10px] font-semibold uppercase text-slate-500">
                  <th className="py-2 px-2.5">Item</th>
                  <th className="py-2 px-2.5 text-right">Qty</th>
                  <th className="py-2 px-2.5 text-right">Unit Price</th>
                  <th className="py-2 px-2.5 text-right">Line Total</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-200">
                {lines.length > 0 ? (
                  lines.map((li) => (
                    <tr key={li.id}>
                      <td className="py-2 px-2.5">
                        <div className="font-medium text-slate-900">
                          {li.product_name || li.description}
                        </div>
                        {li.product_sku ? (
                          <div className="text-[10px] text-slate-500 num-tabular">
                            SKU: {li.product_sku}
                          </div>
                        ) : null}
                      </td>
                      <td className="py-2 px-2.5 text-right num-tabular text-slate-700">
                        {Number(li.quantity).toFixed(2).replace(/\.00$/, '')}
                      </td>
                      <td className="py-2 px-2.5 text-right num-tabular text-slate-700">
                        {formatGhs(li.unit_price)}
                      </td>
                      <td className="py-2 px-2.5 text-right num-tabular font-semibold text-slate-900">
                        {formatGhs(li.line_total)}
                      </td>
                    </tr>
                  ))
                ) : (
                  <tr>
                    <td colSpan={4} className="py-3 px-2.5 text-slate-500 text-center">
                      Commercial invoice total ({formatGhs(invoice.total_amount)})
                    </td>
                  </tr>
                )}
              </tbody>
            </table>
          </div>

          <div className="flex flex-col items-end space-y-1 pt-1">
            <div className="w-56 flex justify-between text-slate-600">
              <span>Subtotal:</span>
              <span className="num-tabular">{formatGhs(invoice.subtotal)}</span>
            </div>
            <div className="w-56 flex justify-between font-bold text-slate-900 text-sm">
              <span>Total:</span>
              <span className="num-tabular">{formatGhs(invoice.total_amount)}</span>
            </div>
            <div className="w-56 flex justify-between text-emerald-700">
              <span>Amount Paid:</span>
              <span className="num-tabular">{formatGhs(invoice.amount_paid)}</span>
            </div>
            <div className="w-56 flex justify-between font-bold text-slate-900 pt-1 border-t border-slate-200">
              <span>Balance Due:</span>
              <span className="num-tabular">{formatGhs(invoice.balance_due)}</span>
            </div>
          </div>

          {invoice.notes ? (
            <div className="pt-2 border-t border-slate-200 text-[11px] text-slate-600">
              <span className="font-semibold text-slate-700">Notes: </span>
              {invoice.notes}
            </div>
          ) : null}
        </div>
      ) : null}
    </Modal>
  )
}
